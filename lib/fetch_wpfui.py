def download(id, ver):
    url = NUGET_URL.format(id=id, ver=ver)
    print("Downloading {} {}...".format(id, ver))
    with urllib.request.urlopen(url, timeout=30) as resp:
        data = resp.read()
    digest = hashlib.sha512(data).hexdigest()
    return data, digest


def extract_dll(nupkg_bytes, dll_name, dest_dir):
    with zipfile.ZipFile(io.BytesIO(nupkg_bytes)) as zf:
        entry = "lib/net462/{}".format(dll_name)
        with zf.open(entry) as src, open(os.path.join(dest_dir, dll_name), "wb") as dst:
            dst.write(src.read())


def main():
    os.makedirs(LIB_DIR, exist_ok=True)
    versions_lines = []
    for id, ver, expected_hash, dll_name in PACKAGES:
        data, digest = download(id, ver)
        if digest != expected_hash:
            print("ERROR: hash mismatch for {} {}".format(id, ver), file=sys.stderr)
            print("  expected: {}".format(expected_hash), file=sys.stderr)
            print("  actual:   {}".format(digest), file=sys.stderr)
            return 1
        extract_dll(data, dll_name, LIB_DIR)
        dll_path = os.path.join(LIB_DIR, dll_name)
        dll_sha256 = hashlib.sha256(open(dll_path, "rb").read()).hexdigest()
        versions_lines.append("{} {} {} sha256={}".format(id, ver, dll_name, dll_sha256))
        print("  OK -> lib/WPF-UI/{}".format(dll_name))

    with open(os.path.join(LIB_DIR, "versions.txt"), "w") as f:
        f.write("# Generated by lib/fetch_wpfui.py - do not edit by hand\n")
        f.write("\n".join(versions_lines) + "\n")

    with open(os.path.join(LIB_DIR, "THIRD-PARTY-NOTICES.txt"), "w") as f:
        f.write(THIRD_PARTY_NOTICES)

    print("Done. {} assemblies written to lib/WPF-UI/".format(len(PACKAGES)))
    return 0


if __name__ == "__main__":
    sys.exit(main())
